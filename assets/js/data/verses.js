/* ==================== ٣) أدوات معالجة النص ==================== */

const TASHKEEL_RE = /[\u0610-\u061A\u064B-\u065F\u0670\u06D6-\u06ED\u0640]/g;
const AR_DIGITS = ['٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩'];

/** تحويل رقم إلى أرقام عربية-هندية (٥٨٧) */
export function toArabicDigits(value) {
  return String(value).replace(/\d/g, (d) => AR_DIGITS[Number(d)]);
}

/**
 * تطبيع نص عربي للبحث: إزالة التشكيل والتطويل، وتوحيد الهمزات
 * والألف المقصورة والتاء المربوطة وأرقام عربية-هندية، مع بناء خريطة
 * (normalized index → original index) لتظليل النتائج في النص الأصلي.
 */
export function normalizeArabic(input) {
  const out = [];
  const map = [];
  for (let i = 0; i < input.length; i += 1) {
    const ch = input[i];
    if (TASHKEEL_RE.test(ch)) {
      TASHKEEL_RE.lastIndex = 0;
      continue;
    }
    TASHKEEL_RE.lastIndex = 0;
    let c = ch;
    if ('أإآٱا'.includes(c)) c = 'ا';
    else if (c === 'ى') c = 'ي';
    else if (c === 'ئ') c = 'ي';
    else if (c === 'ؤ') c = 'و';
    else if (c === 'ة') c = 'ه';
    else if (c === 'ء') c = 'ء';
    else if (AR_DIGITS.includes(c)) c = String(AR_DIGITS.indexOf(c));
    if (/\s/.test(c)) {
      if (out.length === 0 || out[out.length - 1] === ' ') continue;
      c = ' ';
    }
    out.push(c);
    map.push(i);
  }
  // إزالة فراغ أخير
  while (out.length && out[out.length - 1] === ' ') {
    out.pop();
    map.pop();
  }
  return { text: out.join(''), map };
}

/**
 * البحث عن "needle" داخل نص أصلي مع إرجاع المقاطع الأصلية المطابقة
 * (بحيث لا يفقد التظليل التشكيل والرسم الأصلي).
 */
export function findInOriginal(original, needle) {
  const norm = normalizeArabic(original);
  const target = normalizeArabic(needle).text;
  if (!target) return [];
  const hits = [];
  let from = 0;
  for (;;) {
    const idx = norm.text.indexOf(target, from);
    if (idx === -1) break;
    const start = norm.map[idx];
    const lastNormIdx = idx + target.length - 1;
    const end = lastNormIdx + 1 < norm.map.length
      ? norm.map[lastNormIdx + 1]
      : original.length;
    hits.push({ start, end, text: original.slice(start, end) });
    from = idx + Math.max(1, target.length);
  }
  return hits;
}

/* ==================== ٤) بناء نموذج البيانات ==================== */

function resolveChapter(num) {
  return CHAPTERS.find((c) => num >= c.range[0] && num <= c.range[1]) || null;
}

export const VERSES = RAW_VERSES.map(([n, raw], order) => {
  const [sadr, ajz] = raw.split(' ... ').map((s) => s.trim());
  const chapter = resolveChapter(n);
  const text = `${sadr} ... ${ajz}`;
  return Object.freeze({
    n,
    order,
    sadr,
    ajz,
    text,
    label: toArabicDigits(n),
    chapterId: chapter ? chapter.id : null,
    chapterTitle: chapter ? chapter.title : '',
    chapterOrdinal: chapter ? chapter.ordinal : '',
    search: normalizeArabic(text).text,
    weight: sadr.length + ajz.length,
  });
});

/* ربط الأبيات بفصولها */
CHAPTERS.forEach((chapter) => {
  chapter.verses = VERSES.filter((v) => v.chapterId === chapter.id);
  chapter.count = chapter.verses.length;
  chapter.first = chapter.verses[0]?.n ?? 0;
  chapter.last = chapter.verses[chapter.verses.length - 1]?.n ?? 0;
});

export const TOTAL_VERSES = VERSES.length;

/** الوصول السريع للبيت بالرقم (للتنقّل والروابط المباشرة) */
export function verseAt(n) {
  return VERSES.find((v) => v.n === n) || null;
}

export function verseIndex(n) {
  const i = VERSES.findIndex((v) => v.n === n);
  return i === -1 ? 0 : i;
}

